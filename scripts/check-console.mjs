import assert from 'node:assert/strict';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from 'playwright';
import {createFixtureServer} from '../src/server.mjs';
import {createRunManager} from '../src/runs.mjs';
import {executeRun} from '../src/runner.mjs';
const root=resolve('output/playwright',`console-check-${Date.now()}`);
await mkdir(root,{recursive:true});
const saved=JSON.parse(await readFile('docs/examples/corrected-run.json','utf8')).steps;
const runs=await createRunManager({root,configured:()=>true,execute:options=>{
  let cursor=0;
  return executeRun({...options,decide:async(history,observation,task,{signal})=>{
    await delay(160,null,{signal});
    const action=saved[cursor++]?.action;if(!action)throw new Error('scripted_actions_exhausted');
    return {action,model:'scripted-browser-test',continueWith:()=>[]};
  }});
}});
const app=await createFixtureServer({runs,artifactRoot:root});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
const status=()=>fetch(app.origin+'/api/runs').then(r=>r.json());
const readRun=id=>fetch(app.origin+'/api/runs/'+id).then(r=>r.json()).then(r=>r.run);
async function until(predicate,label){const end=Date.now()+45000;while(Date.now()<end){const value=await predicate();if(value)return value;await delay(90);}throw new Error('Timeout: '+label);}
let first,complete,checking;
try{
  await page.goto(app.origin);
  await page.locator('#start').waitFor({state:'visible'});
  await until(()=>page.locator('#start').isEnabled(),'start enabled');
  assert.equal(await page.locator('#stop').isDisabled(),true);
  assert.equal((await status()).runs.length,0);
  const badOrigin=await fetch(app.origin+'/api/runs',{method:'POST',headers:{'Content-Type':'application/json',Origin:'https://unrelated.test'},body:'{"variant":"correct"}'});
  assert.equal(badOrigin.status,403);
  const badType=await fetch(app.origin+'/api/runs',{method:'POST',headers:{'Content-Type':'text/plain'},body:'{"variant":"correct"}'});
  assert.equal(badType.status,415);
  const invalid=await fetch(app.origin+'/api/runs',{method:'POST',headers:{'Content-Type':'application/json'},body:'{"variant":"bad"}'});
  assert.equal(invalid.status,400);
  await page.screenshot({path:resolve(root,'empty-desktop.png'),fullPage:true});
  await page.locator('#start').click();
  first=await until(async()=>{const s=await status();return s.activeId;},'first active id');
  const duplicate=await fetch(app.origin+'/api/runs',{method:'POST',headers:{'Content-Type':'application/json'},body:'{"variant":"correct"}'});
  assert.equal(duplicate.status,409);
  await until(async()=>((await readRun(first)).steps.length>=2),'live actions');
  await until(async()=>await page.locator('#timeline li').count()>=1,'rendered actions');
  await page.locator('#stop').click();
  const stopped=await until(async()=>{const r=await readRun(first);return r.state==='stopped'&&r.reportUrl?r:false;},'stopped partial report');
  const stoppedCount=stopped.steps.length;
  await delay(350);assert.equal((await readRun(first)).steps.length,stoppedCount);
  const partial=await fetch(app.origin+stopped.reportUrl).then(r=>r.text());
  assert.ok(partial.includes('You stopped this run'));
  assert.ok(partial.includes('Checks interrupted by the user'));
  await page.reload();
  await until(()=>page.locator('#start').isEnabled(),'reload idle controls');
  await until(()=>page.locator('#report-link').isVisible(),'restored partial report');
  await page.locator('#start').click();
  complete=await until(async()=>{const s=await status();return s.activeId&&s.activeId!==first?s.activeId:false;},'new run');
  await until(async()=>((await readRun(complete)).steps.length>=3),'live screenshot');
  await until(async()=>await page.locator('#screen-image').evaluate(image=>image.complete&&image.naturalWidth>0),'image loads');
  await page.screenshot({path:resolve(root,'running-desktop.png'),fullPage:true});
  const completed=await until(async()=>{const r=await readRun(complete);return r.state==='completed'?r:false;},'complete run and evidence');
  assert.equal(completed.taskCompleted,true);assert.equal(completed.steps.length,15);
  await until(()=>page.locator('#start').isEnabled(),'idle after complete');
  await until(async()=>await page.locator('#timeline li').count()===15,'all timeline steps rendered');
  const href=await page.locator('#report-link').getAttribute('href');assert.equal(href,completed.reportUrl);
  const report=await fetch(app.origin+href).then(r=>r.text());assert.ok(report.includes('Task completed'));
  const shot=await fetch(app.origin+completed.latestScreenshot);assert.equal(shot.status,200);assert.ok(shot.headers.get('content-type').includes('image/png'));
  await page.screenshot({path:resolve(root,'complete-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:resolve(root,'complete-mobile.png'),fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'no mobile horizontal overflow');
  await page.locator('#run-history button').last().click();
  assert.ok(page.url().includes(first));
  await page.reload();
  await until(()=>page.locator('#report-link').isVisible(),'historical selection after reload');
  assert.ok((await page.locator('#report-link').getAttribute('href')).includes(first));
  await page.setViewportSize({width:1440,height:1050});
  await page.locator('#start').click();
  checking=await until(async()=>{const s=await status();return s.activeId;},'checking cancellation run');
  await until(async()=>((await readRun(checking)).state==='checking'),'checking phase');
  await page.locator('#stop').click();
  const interrupted=await until(async()=>{const r=await readRun(checking);return r.state==='stopped'&&r.reportUrl?r:false;},'cancel during evidence');
  assert.equal(interrupted.taskCompleted,true,'completed task survives cancelled checking');
  const raw=JSON.parse(await readFile(resolve(root,checking,'report.json'),'utf8'));
  assert.equal(raw.cancelled,true);assert.equal(raw.outcome,'agent_inconclusive');assert.equal(raw.evidenceSkipped,'user_stopped');
  await until(()=>page.locator('#start').isEnabled(),'idle after checking cancellation');
  await page.locator('#start').click();
  const immediate=await until(async()=>{const s=await status();return s.activeId;},'immediate cancellation run');
  await page.locator('#stop').click();
  await until(async()=>((await readRun(immediate)).state==='stopped'),'immediate stop');
  assert.equal((await readRun(immediate)).steps.length,0);
  assert.deepEqual(errors,[]);
  const summary={scope:'UI/API/real Chromium fixture integration using injected scripted decisions; no Meta calls or credits.',checks:['start','duplicate rejected','live actions and screenshot','stop','partial report','restart','task completion','report link','mobile','history refresh','cancel during evidence','immediate stop','cross-origin rejection'],runs:(await status()).runs.map(r=>({id:r.id,state:r.state,actions:r.steps.length,taskCompleted:r.taskCompleted})),pageErrors:errors};
  await writeFile(resolve(root,'summary.json'),JSON.stringify(summary,null,2));
  console.log(JSON.stringify({result:'PASS',output:root,...summary}));
}finally{await runs.close();await browser.close();await app.close();}
